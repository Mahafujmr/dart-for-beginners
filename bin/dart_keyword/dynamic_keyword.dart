//dart dynamic keyword
// dynamic - any type value keep
// dynamic - runtime type
void main() {
  dynamic number = 22 ; // this is int type
  print('int type = $number');
  number = 3.44; // this is double type
  print('double type= $number');
  number = 'Tuhin' ; // this is string type
  print('String type = $number');

}
// just same variable name use - keep any type value